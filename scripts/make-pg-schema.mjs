// Builds prisma/schema.postgres.prisma from prisma/schema.prisma by switching the database type.
// The development schema stays on SQLite so local tests need no database server; production
// (Vercel + Neon) is generated from the very same models, so the two cannot drift apart.
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("prisma/schema.prisma", "utf8");
const out = src.replace(
  /datasource db \{[^}]*\}/,
  'datasource db {\n  provider = "postgresql"\n}',
);
if (out === src) throw new Error("Could not find the datasource block in prisma/schema.prisma");
writeFileSync(
  "prisma/schema.postgres.prisma",
  "// GENERATED by scripts/make-pg-schema.mjs from schema.prisma. Do not edit.\n" + out,
);
console.log("Wrote prisma/schema.postgres.prisma");
