/** Staff who are not already managers of a register and may send something to it. */
const except = (list: readonly Role[], skip: readonly Role[]) =>
  list.filter((r) => !skip.includes(r));

const f = (key: string, label: string, extra: Omit<ModuleField, "key" | "label"> = {}) => ({
  key,
  label,
  ...extra,
});
const date = (key = "date", label = "Date", required = true) =>
  f(key, label, { type: "date", required });
const notes = (key = "notes", label = "Details") => f(key, label, { type: "textarea" });
const pick = (key: string, label: string, ...options: string[]) =>
  f(key, label, { type: "select", options });
const reply = f("reply", "Reply / action taken", { type: "textarea", staffOnly: true });
const internal = f("internal", "Internal note", { type: "textarea", private: true });
const amount = (key = "amount", label = "Amount (rupees)") => f(key, label, { type: "number" });

