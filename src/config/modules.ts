export const moduleByKey = (key: string) => MODULES.find((m) => m.key === key);

/** What one role may do with one register. */
export function moduleRights(m: ModuleDef, role: Role) {
  const manage = m.manage.includes(role);
  const viewAll = manage || (m.view?.includes(role) ?? false);
  const submit = m.submit?.includes(role) ?? false;
  const family = (role === "parent" || role === "student") && (m.family ?? false);
  const self = (m.self ?? false) && (STAFF as readonly Role[]).includes(role);
  return { manage, viewAll, submit, family, self, any: viewAll || submit || family || self };
}

export const modulesFor = (role: Role) => MODULES.filter((m) => moduleRights(m, role).any);
