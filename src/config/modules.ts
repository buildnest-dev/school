import type { Role } from "@/types";

/**
 * Registers: the many "keep a list, move it through a few stages" jobs of a school (visitors,
 * repairs, discipline, clubs...). One table, one API and one screen serve all of them; this file
 * is the single place that says what each one holds and who may see or change it.
 */
export type FieldType = "text" | "textarea" | "date" | "time" | "number" | "select" | "link";

export interface ModuleField {
  key: string;
  label: string;
  type?: FieldType;
  options?: readonly string[];
  required?: boolean;
  /** Only managers fill it in; the person who sent the record can read it (for example a reply). */
  staffOnly?: boolean;
  /** Only managers see it at all. */
  private?: boolean;
}

export interface ModuleDef {
  key: string;
  title: string;
  description: string;
  group: ModuleGroup;
  /** Sees every record, adds, edits, changes the stage and deletes. */
  manage: readonly Role[];
  /** Sees every record, changes nothing. */
  view?: readonly Role[];
  /** Adds records and sees only their own; may change them while still at the first stage. */
  submit?: readonly Role[];
  /** Parents and students see the records about their own child / themselves. */
  family?: boolean;
  /** Staff see the records about themselves. */
  self?: boolean;
  student?: "required" | "optional";
  staff?: "required" | "optional";
  /** What the title box is called. */
  titleLabel: string;
  statuses: readonly string[];
  fields: readonly ModuleField[];
  /** Two bookings of the same thing may not overlap on one day. */
  noOverlap?: { resource: string; from: string; to: string; free: readonly string[] };
}

