export const screenHref = (s: ScreenDef) =>
  s.path ? `${AREA_ROOT[s.area]}/${s.path}` : AREA_ROOT[s.area];

export const screensFor = (area: Area) => SCREENS.filter((s) => s.area === area);

/** Match URL segments (below the area root) against the screen table. */
export function matchScreen(area: Area, segments: readonly string[]) {
  for (const s of screensFor(area)) {
    const parts = s.path === "" ? [] : s.path.split("/");
    if (parts.length !== segments.length) continue;
    const params: Record<string, string> = {};
    const ok = parts.every((p, i) => {
      const seg = segments[i] ?? "";
      if (p.startsWith(":")) {
        params[p.slice(1)] = decodeURIComponent(seg);
        return true;
      }
      return p === seg;
    });
    if (ok) return { screen: s, params };
  }
  return null;
}

/** Static (non-dynamic) paths, for generateStaticParams. */
export const staticSlugs = (area: Area) =>
  screensFor(area)
    .filter((s) => !s.path.includes(":"))
    .map((s) => (s.path === "" ? [] : s.path.split("/")));

export const canAccess = (role: Role, s: ScreenDef) => s.roles.includes(role);
