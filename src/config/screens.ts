import type { Area, Role } from "@/types";

/**
 * Single source of truth for application screens: routes, roles, navigation, status and the
 * Master Feature List sections each screen covers. The sidebar, route guard, route table
 * and docs/SCREEN_INVENTORY.md are all derived from (or checked against) this file.
 */
export type ScreenStatus = "implemented" | "partial" | "planned";

export interface ScreenDef {
  id: string;
  area: Area;
  /** Path below the area root. `:name` segments are dynamic. Empty string = area home. */
  path: string;
  title: string;
  description: string;
  roles: readonly Role[];
  /** Appears in the sidebar when set. */
  nav?: {
    group: string;
    icon: string;
    order: number;
    /** Short label for the mobile bottom bar. */ short?: string;
  };
  status: ScreenStatus;
  /** Master Feature List section numbers (e.g. "5" = Certificates). */
  features: readonly string[];
}

